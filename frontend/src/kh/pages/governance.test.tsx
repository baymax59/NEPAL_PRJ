// Reports and governance: signed reports, checking a report file, two-step verification at login. Fictional data.

import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import type { ReactNode } from 'react'
import { describe, expect, it, vi } from 'vitest'
import { AuthContext, type AuthValue } from '../../auth/context'
import { LoginPage } from '../../pages/LoginPage'
import { renderWithProviders } from '../../test/render'
import { kh } from '../api'
import { SignedReports } from '../case/SignedReports'
import type { CaseDetail, ReportCheck, ReportsView } from '../types'
import { VerifyReportPage } from './VerifyReportPage'

vi.mock('../api', () => ({
  kh: { reports: vi.fn(), generateReport: vi.fn(), verifyReport: vi.fn(), reportDownloadLink: vi.fn(), verifyReportFile: vi.fn() },
  newKey: () => 'key',
}))

const DETAIL = {
  id: 'case-1',
  display_id: 'KH-2026-0009',
  can: { add_files: true },
} as unknown as CaseDetail
const VERSION = {
  id: 'export-1', display_id: 'RPT-0001', version_number: 2, report_type: 'case_report', title: 'Case report', purpose: 'Fictional: for review.',
  file_name: 'KH-2026-0009-RPT-0001-v2.pdf', sha256: 'c'.repeat(64), size_bytes: 20480, page_count: 3, as_of_entry: 12,
  case_id: 'case-1', withheld_entries: 1,
  generated_by: { id: 'u1', username: 'inv.arun', display_name: 'SI Arun (fictional)' }, generated_at: '2026-11-08T09:00:00Z', sealed: false,
  last_check: { result: 'match', method: 'stored_copy', computed_sha256: 'c'.repeat(64), checked_at: '2026-11-08T09:05:00Z', checked_by: null },
}

/** Mantine's FileInput is a button in front of a hidden file field: files go to the field. */
const fileField = () => document.querySelector('input[type="file"]') as HTMLInputElement

function withQuery(ui: ReactNode) {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
  return renderWithProviders(<QueryClientProvider client={client}>{ui}</QueryClientProvider>)
}

describe('SignedReports', () => {
  it('lists report versions with their check and the entry of the history they describe, and generates a new one', async () => {
    vi.mocked(kh.reports).mockResolvedValue({ case: {}, entries: 12, reports: [VERSION], report_types: [] } as unknown as ReportsView)
    vi.mocked(kh.generateReport).mockResolvedValue({ entry: 13, report: { ...VERSION, version_number: 3, as_of_entry: 12 } } as never)
    withQuery(<SignedReports detail={DETAIL} />)
    expect(await screen.findByText('RPT-0001 · version 2')).toBeInTheDocument()
    expect(screen.getByText('intact')).toBeInTheDocument()
    expect(screen.getByText(/1 withheld/)).toBeInTheDocument()
    expect(screen.getByRole('link', { name: 'Entry 12' })).toHaveAttribute('href', '/kh/case/case-1/history#entry-12')
    await userEvent.click(screen.getByRole('button', { name: 'Generate a signed PDF' }))
    await userEvent.type(screen.getByLabelText(/Purpose/), 'Fictional: monthly review.')
    await userEvent.click(screen.getByRole('button', { name: 'Generate' }))
    expect(vi.mocked(kh.generateReport)).toHaveBeenCalledWith('case-1', { report_type: 'case_report', purpose: 'Fictional: monthly review.' }, 'key')
  })
})

describe('VerifyReportPage', () => {
  it('says whether a file is exactly a generated report', async () => {
    vi.mocked(kh.verifyReportFile).mockResolvedValue({
      result: 'match', method: 'submitted_copy', computed_sha256: 'c'.repeat(64), recorded_sha256: 'c'.repeat(64), checked_at: '2026-11-08T09:10:00Z',
      report: VERSION, message: 'This file is exactly the report Knight Hawk generated: not one byte has changed.',
    } as ReportCheck)
    withQuery(<VerifyReportPage />)
    const file = new File(['%PDF-1.4 fictional'], 'copy.pdf', { type: 'application/pdf' })
    await userEvent.upload(fileField(), file)
    await userEvent.click(screen.getByRole('button', { name: 'Check' }))
    expect(await screen.findByText('Genuine: exactly the report Knight Hawk generated')).toBeInTheDocument()
    expect(screen.getByText('RPT-0001, version 2: Case report')).toBeInTheDocument()
  })

  it('shows a changed file as not recognised', async () => {
    vi.mocked(kh.verifyReportFile).mockResolvedValue({
      result: 'unknown', method: 'submitted_copy', computed_sha256: 'f'.repeat(64), recorded_sha256: null, checked_at: '2026-11-08T09:10:00Z',
      report: null, message: 'No report generated by Knight Hawk in your organisation has exactly this content.',
    } as ReportCheck)
    withQuery(<VerifyReportPage />)
    await userEvent.upload(fileField(), new File(['changed'], 'copy.pdf', { type: 'application/pdf' }))
    await userEvent.click(screen.getByRole('button', { name: 'Check' }))
    expect(await screen.findByText('Not recognised')).toBeInTheDocument()
  })
})

describe('LoginPage', () => {
  it('asks for the code when the account uses two-step verification', async () => {
    const login = vi.fn().mockResolvedValue({ mfaTicket: 'ticket-1' })
    const loginSecondStep = vi.fn().mockResolvedValue(undefined)
    const auth = { user: null, loading: false, login, loginSecondStep, logout: vi.fn(), reload: vi.fn(), hasRole: () => false } as AuthValue
    renderWithProviders(
      <AuthContext value={auth}>
        <LoginPage />
      </AuthContext>,
    )
    await userEvent.type(screen.getByLabelText(/Username/), 'sup.kh')
    await userEvent.type(screen.getByLabelText(/Password/), 'fictional-password')
    await userEvent.click(screen.getByRole('button', { name: 'Log in' }))
    expect(await screen.findByText('Two-step verification')).toBeInTheDocument()
    const boxes = screen.getAllByRole('textbox')
    await userEvent.type(boxes[0], '123456')
    await userEvent.click(screen.getByRole('button', { name: 'Verify and log in' }))
    expect(loginSecondStep).toHaveBeenCalledWith('ticket-1', '123456')
  })
})
