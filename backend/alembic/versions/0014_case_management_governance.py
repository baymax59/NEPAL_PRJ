# The hash of one event: the previous hash and every field, in a fixed order, separated by "|". Missing values are
# empty strings (concat_ws would skip NULLs and shift the fields). details::text is jsonb's own, stable spelling.
AUDIT_HASH = """
    CREATE FUNCTION cm_audit_hash(previous text, e audit_events) RETURNS text LANGUAGE sql STABLE AS $$
        SELECT encode(sha256(convert_to(concat_ws('|',
            previous, e.chain_seq::text, e.id::text,
            to_char(e.occurred_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'),
            coalesce(e.user_id::text, ''), coalesce(e.username, ''), e.action, e.outcome,
            coalesce(e.target_type, ''), coalesce(e.target_id, ''), coalesce(e.client_ip, ''), e.details::text), 'UTF8')), 'hex')
    $$
"""
BACKFILL = """
    DO $$
    DECLARE
        e audit_events;
        n bigint := 0;
        previous text := repeat('0', 64);
    BEGIN
        FOR e IN SELECT * FROM audit_events WHERE action LIKE 'cm.%' ORDER BY id LOOP
            n := n + 1;
            e.chain_seq := n;
            UPDATE audit_events SET chain_seq = n, prev_hash = previous, hash = cm_audit_hash(previous, e)
                WHERE id = e.id RETURNING hash INTO previous;
        END LOOP;
    END $$
"""
AUDIT_CHAIN = """
    CREATE FUNCTION cm_audit_chain() RETURNS trigger LANGUAGE plpgsql AS $$
    DECLARE
        last_seq bigint;
        last_hash text;
    BEGIN
        IF NEW.action NOT LIKE 'cm.%' THEN
            NEW.chain_seq := NULL; NEW.prev_hash := NULL; NEW.hash := NULL;  -- outside the chain
            RETURN NEW;
        END IF;
        PERFORM pg_advisory_xact_lock(724300107);  -- one transaction at a time extends the chain
        SELECT chain_seq, hash INTO last_seq, last_hash FROM audit_events
            WHERE chain_seq IS NOT NULL ORDER BY chain_seq DESC LIMIT 1;
        NEW.chain_seq := coalesce(last_seq, 0) + 1;
        NEW.prev_hash := coalesce(last_hash, repeat('0', 64));
        NEW.hash := cm_audit_hash(NEW.prev_hash, NEW);
        RETURN NEW;
    END $$
"""
AUDIT_PERMANENT = """
    CREATE FUNCTION cm_audit_chain_permanent() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
        IF OLD.chain_seq IS NOT NULL THEN
            RAISE EXCEPTION 'Case Management: % of an audit event in the chain is not allowed: it is permanent', TG_OP
                USING ERRCODE = 'restrict_violation';
        END IF;
        IF TG_OP = 'DELETE' THEN
            RETURN OLD;  -- events outside the chain follow their retention rule (Step 14.3)
        END IF;
        IF NEW.chain_seq IS NOT NULL OR NEW.hash IS NOT NULL OR NEW.action LIKE 'cm.%' THEN
            RAISE EXCEPTION 'Case Management: an audit event can''t be moved into the chain' USING ERRCODE = 'restrict_violation';
        END IF;
        RETURN NEW;
    END $$
"""
